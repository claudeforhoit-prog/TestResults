    '    exit 2\n',
    '  fi\n',
    '  for CS_X in "$RD" "$LOGDIR"; do\n',
    '    if ! can_write "$CS_X"; then\n',
    '      say "==== 1 MB cannot be written in $CS_X (disk full or disk quota of the account, $(free_mb "$CS_X") MB free on the disk). Nothing started."\n',
    '      say "     Set the jump VM work folder or log folder in tcgen to a folder with free space, paste block A (work folder) and generate again."\n',
    '      exit 2\n',
    '    fi\n',
    '  done\n',
    '  CS_N=0; CS_L=\n',
    '  JOBS=$LOGDIR/tcrun-$RUNID-jobs.csv\n',
    '  jobs_head\n',
    '  old_claims\n',
    '  for CS_CH in $(chains); do\n',
    '    CS_F=$(chfile "$CS_CH")\n',
    '    if [ -f "$RD/$CS_F.state" ] || [ -f "$RD/$CS_F.pid" ]; then\n',
    '      say "==== $CS_F: run $RUNID was already started on this jump VM. Not started again. Generate again in tcgen to run again."\n',
    '      continue\n',
    '    fi\n',
    '    CH=$CS_CH; CHF=$CS_F\n',
    '    CS_B=$(host_block)\n',
    '    if [ -n "$CS_B" ]; then\n',
    '      say "==== $CS_F: not started. $CS_B"\n',
    '      continue\n',
    '    fi\n',
    '    claim_plan_starts "$CS_CH" | sed "s/^/==== $CS_F: /"\n',
    '    setsid sh "$D/tcrun" run "$PLAN" "$CS_CH" > "$RD/$CS_F.out" 2>&1 < /dev/null &\n',
    '    CS_N=$((CS_N + 1)); CS_L="$CS_L $CS_F:$!"\n',
    '  done\n',
    '  # wait until every runner has written its state file (at most 30 s. a runner that ended at once is not waited for)\n',
    '  CS_I=0\n',
    '  while [ "$CS_N" -gt 0 ] && [ "$CS_I" -lt 30 ]; do\n',
    '    CS_W=0\n',
    '    for CS_X in $CS_L; do\n',
    '      CS_F=${CS_X%%:*}\n',
    '      [ -f "$RD/$CS_F.state" ] && continue\n',
    '      if [ "$CS_I" -ge 3 ] && [ ! -f "$RD/$CS_F.pid" ] && ! kill -0 "${CS_X#*:}" 2>/dev/null; then continue; fi\n',
    '      CS_W=1\n',
    '    done\n',
    '    [ "$CS_W" = 0 ] && break\n',
    '    sleep 1\n',
    '    CS_I=$((CS_I + 1))\n',
    '  done\n',
    '  for CS_X in $CS_L; do\n',
    '    CS_F=${CS_X%%:*}\n',
    '    if [ -f "$RD/$CS_F.state" ] && [ "$(state_of "$RD" "$CS_F")" = queued ]; then\n',
