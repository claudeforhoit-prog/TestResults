    '    return 0\n',
    '  done\n',
    '  return 0\n',
    '}\n',
    'queue_wait() {      # wait until the runners of this ESX host that were alive when this one started ($QWAIT) have ended.\n',
    '                    # 1 = this run does not start (stop request, or one of them did not end as done)\n',
    '  STEP=queued\n',
    '  log "queued: run(s)$QWAIT still work for this ESX host. This run starts when they have ended as done"\n',
    '  for QW_R in $QWAIT; do\n',
    '    QW_E=$(run_end "$QW_R" "$CH")\n',
    '    setstate queued "waiting for run $QW_R of this ESX host to end${QW_E:+ (about $(tstr "$QW_E"), 1 min after its last job start)}"\n',
    '    while alive "$D/runs/$QW_R/$CHF.pid" && [ ! -f "$STOPF" ]; do\n',
    '      sleep 5\n',
    '    done\n',
    '    if [ -f "$STOPF" ]; then                      # looked at first: a stop request often ends both runners at once\n',
    '      R_DONE=1\n',
    '      stopped "while this run was queued behind run $QW_R. Nothing of this run was started."\n',
    '      return 1\n',
    '    fi\n',
    '    QW_S=$(state_of "$D/runs/$QW_R" "$CHF")\n',
    '    if [ "$QW_S" != done ]; then\n',
    '      R_DONE=1\n',
    '      pause "run $QW_R of this ESX host ended as $QW_S, not as done. Nothing of this run was started. Look at that run (sh $D/tcrun status), then generate again in tcgen."\n',
    '      return 1\n',
    '    fi\n',
    '    log "queued: run $QW_R ended as done"\n',
    '  done\n',
    '  return 0\n',
    '}\n',
    '\n',
    '# ---------------------------------------------------------------- start, status, stop, key\n',
    'running_for() {     # print the RUNID of a run that is still running for this ESX host\n',
    '  for RF in "$D"/runs/*/"$1".pid; do\n',
    '    [ -f "$RF" ] || continue\n',
    '    if alive "$RF"; then\n',
    '      basename "$(dirname "$RF")"\n',
    '      return 0\n',
    '    fi\n',
    '  done\n',
    '  return 1\n',
    '}\n',
    'cmd_start() {\n',
    '  load_plan "$1"\n',
