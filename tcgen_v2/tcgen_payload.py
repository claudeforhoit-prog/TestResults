    '    say "${OR_D##*/}"\n',
    '  done\n',
    '}\n',
    'host_block() {      # prints why run $RUNID must not be started for ESX host $CH now (prints nothing when it may start).\n',
    '                    # Needs PLAN, RUNID, CH, CHF. A run that ended as done may have left lines whose times have passed:\n',
    '                    # the next run removes them (take_over). A run that ended in another way may have left lines of jobs\n',
    '                    # that have not started yet: those must be removed first\n',
    '  for HB_R in $(open_runs); do\n',
    '    HB_D=$D/runs/$HB_R\n',
    '    HB_S=$(state_of "$HB_D" "$CHF")\n',
