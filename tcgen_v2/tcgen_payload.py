    '# ---------------------------------------------------------------- runs of the same ESX host: queue, open cases\n',
    '# One runner at a time works for an ESX host. A run that is started while another run still works for the same ESX host\n',
    '# waits in the queue and starts when that run has ended as done.\n',
    '# An "open case" is a case whose crontab lines are on the hosts (its monitoring may run) after its runner ended:\n',
    '#   <run>/<host>.work/times holds "<case number> <monitoring start> <job start>" from the registration until the lines are removed.\n',
    'state_of() {        # state_of <run dir> <host file name>: state of that runner: running, queued, done, paused, stopped, cancelled,\n',
    '                    # died (the state says running or queued, but the runner is gone) or none\n',
    '  SO_S=$(grep \'^state=\' "$1/$2.state" 2>/dev/null | cut -d= -f2-)\n',
    '  case "$SO_S" in\n',
    '    running|queued) alive "$1/$2.pid" || SO_S=died ;;\n',
    '    "") SO_S=none ;;\n',
    '  esac\n',
    '  say "$SO_S"\n',
    '}\n',
    'open_case_name() {  # open_case_name <run dir> <host file name>: name of the open case ("" when there is none)\n',
    '  OC_Q=$(cut -d\' \' -f1 "$1/$2.work/times" 2>/dev/null)\n',
    '  case "$OC_Q" in ""|*[!0-9]*) return 0 ;; esac\n',
    '  OC_N=$(grep "^CASE $OC_Q " "$1/plan" 2>/dev/null | head -n 1 | cut -d\' \' -f4)\n',
    '  say "${OC_N:-number $OC_Q}"\n',
    '}\n',
    'open_runs() {       # open_runs [done]: run ids (other than this run) whose runner for ESX host $CHF has ended with a case open.\n',
    '                    # "done": only those that ended as done (a case that was not checked and has no end time)\n',
    '  for OR_F in "$D"/runs/*/"$CHF".work/times; do\n',
    '    [ -s "$OR_F" ] || continue\n',
    '    OR_D=${OR_F%/*}; OR_D=${OR_D%/*}\n',
    '    [ "${OR_D##*/}" = "$RUNID" ] && continue\n',
    '    alive "$OR_D/$CHF.pid" && continue\n',
    '    if [ "$1" = done ] && [ "$(state_of "$OR_D" "$CHF")" != done ]; then continue; fi\n',
    '    say "${OR_D##*/}"\n',
    '  done\n',
    '}\n',
    'host_block() {      # prints why run $RUNID must not be started for ESX host $CH now (prints nothing when it may start).\n',
    '                    # Needs PLAN, RUNID, CH, CHF\n',
    '  HB_AUTO=1\n',
    '  HB_Q=$(cseqs "$CH" | head -n 1)\n',
    '  grep -q "^START $HB_Q " "$PLAN" && HB_AUTO=\n',
    '  for HB_R in $(open_runs); do\n',
    '    HB_D=$D/runs/$HB_R\n',
    '    HB_S=$(state_of "$HB_D" "$CHF")\n',
    '    HB_C=$(open_case_name "$HB_D" "$CHF")\n',
    '    if [ "$HB_S" != done ]; then\n',
    '      say "run $HB_R of this ESX host ended as $HB_S and left case $HB_C open (crontab lines on the hosts, its monitoring may run). Close it first: sh $D/tcrun cancel $CHF"\n',
    '      return 0\n',
    '    fi\n',
    '    if [ -n "$HB_AUTO" ]; then\n',
    '      say "case $HB_C of run $HB_R is still open on this ESX host (it was not checked and has no end time), and the first case of this run has no start time: tcrun cannot tell when that job ends. Give the first case a start time in tcgen, or close the open case first: sh $D/tcrun cancel $CHF"\n',
    '      return 0\n',
    '    fi\n',
    '  done\n',
    '  [ -n "$HB_AUTO" ] || return 0\n',
    '  for HB_F in "$D"/runs/*/"$CHF".pid; do           # a run that still works here and will leave its last case open\n',
    '    alive "$HB_F" || continue\n',
    '    HB_D=${HB_F%/*}\n',
    '    [ "${HB_D##*/}" = "$RUNID" ] && continue\n',
    '    HB_L=$(grep "^CASE [0-9]* $(bre "$CH") " "$HB_D/plan" 2>/dev/null | tail -n 1 | cut -d\' \' -f2)\n',
    '    [ -n "$HB_L" ] || continue\n',
    '    grep -q "^NOCHK $HB_L 0 " "$HB_D/plan" 2>/dev/null || continue\n',
    '    grep -q "^MAXWAIT $HB_L [1-9]" "$HB_D/plan" 2>/dev/null && continue\n',
    '    say "run ${HB_D##*/} still works for this ESX host and its last case is not checked and has no end time, and the first case of this run has no start time: tcrun cannot tell when that job ends. Give the first case of this run a start time in tcgen"\n',
    '    return 0\n',
    '  done\n',
    '  return 0\n',
