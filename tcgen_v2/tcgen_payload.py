    '  if [ "$CH" != "-" ] && ! addr_ok "$EADDR"; then say "tcrun: bad ESX address in the plan for $CH"; exit 2; fi\n',
    '  ssh_setup\n',
    '  [ -s "$RES" ] || say "case,esx,apply,begin,vms_on,monitor_start,job_start,first_seen,job_end,monitor_stop,end,status" > "$RES"\n',
    '  jobs_head\n',
    '  log "tcrun $TCRUN_VERSION run $RUNID, esx $CHF ($EADDR), $TOTAL case(s), pid $$"\n',
    '  old_claims\n',
    '  claim_plan_starts "$CH" | while IFS= read -r CR_LINE; do log "$CR_LINE"; done\n',
    '  CR_GO=1\n',
    '  if [ -n "$QWAIT" ]; then\n',
    '    queue_wait || CR_GO=\n',
    '  fi\n',
    '  if [ -n "$CR_GO" ]; then\n',
    '    CR_B=$(host_block)\n',
    '    if [ -n "$CR_B" ]; then\n',
    '      R_DONE=1\n',
    '      pause "$CR_B. Nothing of this run was started."\n',
    '      CR_GO=\n',
    '    fi\n',
    '  fi\n',
    '  if [ -n "$CR_GO" ]; then\n',
    '    TAKE=$(open_runs done)\n',
    '    [ -n "$TAKE" ] && log "run(s) $(say $TAKE) left crontab lines on the hosts of this ESX host. They are removed $PREP min before the first job start of this run"\n',
    '  fi\n',
    '  log "settings: start times of the plan are not changed. Settings and VM power of a case that differs from the hosts are changed $PREP min before its job start, config snapshot $SNAPLEAD min before every job start, monitoring start $LEAD min before the job start, power on wait $PON_WAIT min, boot wait $BOOT_WAIT min, shutdown wait $SHUT_WAIT min"\n',
    '  [ -n "$CR_GO" ] && setstate running "started"\n',
    '  for SEQ in ${CR_GO:+$SEQS}; do\n',
    '    IDX=$((IDX + 1))\n',
    '    CNAME=$(cname "$SEQ")\n',
    '    if [ -f "$STOPF" ]; then\n',
    '      R_DONE=1\n',
    '      stopped "before case $CNAME"\n',
    '      break\n',
    '    fi\n',
    '    run_case || break\n',
    '  done\n',
    '  release_mine "$CHF"\n',
    '  if [ -z "$HOW" ]; then\n',
    '    # the runner stays until 1 min after the last job start: a run that is queued behind it removes its lines then\n',
    '    CR_LAST=$(cut -d\' \' -f3 "$W/times" 2>/dev/null | sort -n | tail -n 1)\n',
    '    case "$CR_LAST" in ""|*[!0-9]*) CR_LAST= ;; esac\n',
    '    if [ -n "$CR_LAST" ] && [ "$(now)" -lt $((CR_LAST + 60)) ]; then\n',
    '      STEP=wait-last-job\n',
    '      setstate running "every case is handled. Waiting until 1 min after the last job start ($(tstr "$CR_LAST")), then this runner ends"\n',
    '      if ! wait_until $((CR_LAST + 60)); then\n',
    '        CR_ALL=1\n',
    '        stopped "while the runner waited for the last job start. The crontab lines stay registered: the jobs start at their times. To remove them: sh $D/tcrun cancel $CHF"\n',
    '      fi\n',
    '    fi\n',
    '  fi\n',
    '  if [ -z "$HOW" ]; then\n',
    '    STEP=end\n',
    '    log "run finished: $TOTAL case(s), $NREG job case(s) registered, $NREGBAD not registered"\n',
    '    CR_T="all $TOTAL case(s) finished: $NREG job case(s) registered"\n',
    '    [ "$NREGBAD" -gt 0 ] && CR_T="$CR_T, $NREGBAD NOT registered (see $JOBS)"\n',
    '    setstate done "$CR_T. The crontab lines stay on the hosts until the next run of this ESX host registers its first lines, or sh $D/tcrun cancel $CHF"\n',
    '    return 0\n',
    '  fi\n',
    '  jobs_rest\n',
    '  CR_I=0; CR_REST=\n',
    '  for CR_S in $SEQS; do\n',
    '    CR_I=$((CR_I + 1))\n',
    '    [ "$CR_I" -ge "$IDX" ] && CR_REST="$CR_REST $(cname "$CR_S")"\n',
    '  done\n',
    '  if [ -n "$CR_ALL" ]; then\n',
    '    log "run ended ($HOW) after every case was handled: $NREG job case(s) registered, $NREGBAD not registered (see $JOBS)"\n',
    '  elif [ "$IDX" = 0 ]; then\n',
    '    log "run ended ($HOW) before its first case. Not finished:$CR_REST"\n',
    '    log "the cases that are registered start at their times (see $JOBS). To go on with the others: sh $D/tcrun cancel $CHF (removes the lines that are left), fix the cause, generate again in tcgen and paste block S"\n',
    '  else\n',
    '    log "run ended ($HOW) at case $CNAME. Not finished:$CR_REST"\n',
    '    log "the cases that are registered start at their times (see $JOBS). To go on with the others: sh $D/tcrun cancel $CHF (removes the lines that are left), fix the cause, generate again in tcgen and paste block S"\n',
    '  fi\n',
    '  setstate "$HOW" "$HOW_TEXT"\n',
    '  return 1\n',
    '}\n',
    '\n',
    '# ---------------------------------------------------------------- runs of the same ESX host: queue, lines left on the hosts\n',
    '# One runner at a time works for an ESX host. A run that is started while another run still works for the same ESX host\n',
    '# waits in the queue and starts when that run has ended as done.\n',
    '# <run>/<host>.work/times holds one line "<case number> <first start time> <job start>" for every case whose crontab\n',
    '# lines are on the hosts, from the registration until the lines are removed (by the next run or by cancel).\n',
    '# A fourth field lists the hosts where the lines could not be removed ("vm1,vm2,@esx"): only those still have them.\n',
    'run_end() {         # run_end <run id> <ESX host of the plan>: when the runner of that run for the ESX host ends: 1 min\n',
    '                    # after its latest job start (epoch; "" when its plan has no job start for the host)\n',
    '  RE_M=\n',
    '  for RE_S in $(grep "^CASE [0-9]* $(bre "$2") " "$D/runs/$1/plan" 2>/dev/null | cut -d\' \' -f2); do\n',
    '    RE_T=$(grep "^START $RE_S " "$D/runs/$1/plan" 2>/dev/null | head -n 1 | cut -d\' \' -f3)\n',
    '    case "$RE_T" in ""|*[!0-9]*) continue ;; esac\n',
    '    if [ -z "$RE_M" ] || [ "$RE_T" -gt "$RE_M" ]; then RE_M=$RE_T; fi\n',
    '  done\n',
    '  [ -n "$RE_M" ] && say $((RE_M / 60 * 60 + 60))\n',
    '  return 0\n',
    '}\n',
    'state_of() {        # state_of <run dir> <host file name>: state of that runner: running, queued, done, paused, stopped, cancelled,\n',
    '                    # died (the state says running or queued, but the runner is gone) or none\n',
    '  SO_S=$(grep \'^state=\' "$1/$2.state" 2>/dev/null | cut -d= -f2-)\n',
    '  case "$SO_S" in\n',
    '    running|queued) alive "$1/$2.pid" || SO_S=died ;;\n',
    '    "") SO_S=none ;;\n',
    '  esac\n',
    '  say "$SO_S"\n',
    '}\n',
    'open_case_name() {  # open_case_name <run dir> <host file name>: the cases of that run whose crontab lines are on the hosts:\n',
    '                    # the name of the first one and how many more ("" when there is none)\n',
    '  OC_N=0; OC_FIRST=\n',
    '  for OC_Q in $(cut -d\' \' -f1 "$1/$2.work/times" 2>/dev/null); do\n',
    '    case "$OC_Q" in ""|*[!0-9]*) continue ;; esac\n',
    '    OC_N=$((OC_N + 1))\n',
    '    [ -n "$OC_FIRST" ] && continue\n',
    '    OC_FIRST=$(grep "^CASE $OC_Q " "$1/plan" 2>/dev/null | head -n 1 | cut -d\' \' -f4)\n',
    '    [ -n "$OC_FIRST" ] || OC_FIRST="number $OC_Q"\n',
    '  done\n',
    '  [ "$OC_N" -gt 0 ] || return 0\n',
    '  if [ "$OC_N" = 1 ]; then say "$OC_FIRST"; else say "$OC_FIRST and $((OC_N - 1)) more"; fi\n',
    '}\n',
    'open_runs() {       # open_runs [done]: run ids (other than this run) whose runner for ESX host $CHF has ended with a case open.\n',
    '                    # "done": only those that ended as done (a case that was not checked and has no end time)\n',
