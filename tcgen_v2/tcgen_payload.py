    '        else:\n',
    '            out("usage: tcgen_apply.py check | prepare <tag> | poweron <vm> [seconds] | poweroff <vm> [seconds] | lpage <vm> | "\n',
    '                "lpagewait <vm> [seconds] | rollback <tag> | snapshot   (spec on stdin)")\n',
    '            result("error", "bad arguments")\n',
    '            return 1\n',
    '    except Fail as e:\n',
    '        result("error", str(e))\n',
    '        return 1\n',
    '    except Exception as e:          # an unexpected error must still end with a result line for the runner\n',
    '        result("error", "unexpected %s: %s" % (type(e).__name__, e))\n',
    '        return 1\n',
    '    finally:\n',
    '        if lock:\n',
    '            drop_lock(lock)\n',
    '        save_log(argv)\n',
    '    return 0\n',
    '\n',
    '\n',
    'if __name__ == "__main__":\n',
    '    sys.exit(main(sys.argv))\n',
