    '                f.write(line + "\\n")\n',
    '    except (IOError, OSError):\n',
    '        pass\n',
    '\n',
    '\n',
    'def run(argv, timeout=120):\n',
    '    try:\n',
    '        p = subprocess.Popen(argv, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)\n',
    '    except OSError as e:\n',
    '        raise Fail("cannot run %s: %s" % (argv[0], e))\n',
    '    try:\n',
    '        data, _ = p.communicate(timeout=timeout)\n',
    '    except subprocess.TimeoutExpired:\n',
    '        p.kill()\n',
    '        p.communicate()\n',
    '        raise NoAnswer("no answer in %d s: %s" % (timeout, " ".join(argv)))\n',
    '    return p.returncode, data.decode("utf-8", "replace")\n',
    '\n',
    '\n',
    'def short(text):\n',
    '    """One line that says why a command failed: the msg of a vim-cmd fault, else the last line with text."""\n',
    '    m = re.search(r\'msg\\s*=\\s*"(.*)"\', text)\n',
    '    if m:\n',
    '        return m.group(1)[:300]\n',
    '    lines = [x.strip() for x in text.strip().splitlines() if x.strip() not in ("", "{", "}")]\n',
    '    return (lines[-1] if lines else "")[:300]\n',
    '\n',
    '\n',
    'def failed(rc, text):\n',
    '    return rc != 0 or "fault" in text.lower()\n',
    '\n',
    '\n',
    '# ---------------------------------------------------------------- lock (one tcgen_apply at a time on a host)\n',
    'def pid_alive(pid):\n',
    '    try:\n',
    '        os.kill(pid, 0)\n',
    '    except OSError as e:\n',
    '        return getattr(e, "errno", 0) == 1          # EPERM: the process exists\n',
    '    return True\n',
    '\n',
    '\n',
    'def take_lock():\n',
    '    if not os.path.isdir(TMP):\n',
    '        os.makedirs(TMP)\n',
    '    path = os.path.join(TMP, "lock")\n',
    '    for _ in range(3):\n',
    '        try:\n',
    '            fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)\n',
    '            os.write(fd, str(os.getpid()).encode("ascii"))\n',
    '            os.close(fd)\n',
    '            return path\n',
    '        except OSError:\n',
    '            try:\n',
    '                with open(path) as f:\n',
    '                    pid = int(f.read().strip() or "0")\n',
    '            except (IOError, OSError, ValueError):\n',
    '                pid = 0\n',
    '            if pid and pid != os.getpid() and pid_alive(pid):\n',
    '                raise Fail("another tcgen_apply.py (pid %d) is running on this host. Try again when it has ended." % pid)\n',
    '            try:\n',
    '                os.remove(path)\n',
    '            except OSError:\n',
    '                pass\n',
    '    raise Fail("cannot create the lock file %s" % path)\n',
    '\n',
    '\n',
    'def drop_lock(path):\n',
    '    try:\n',
    '        os.remove(path)\n',
    '    except OSError:\n',
    '        pass\n',
    '\n',
    '\n',
    '# ---------------------------------------------------------------- spec\n',
    'def read_spec(data):\n',
    '    spec = {"vms": [], "host": [], "set": {}, "off": [], "opt": {"shutdown_wait": 600}}\n',
    '    for raw in data.decode("ascii", "replace").split("\\n"):\n',
    '        line = raw.rstrip("\\r")\n',
    '        if not line.strip() or line.startswith("#"):\n',
    '            continue\n',
    '        word, _, rest = line.partition(" ")\n',
    '        if word == "vm":\n',
    '            name = rest.strip()\n',
    '            if not name or name in spec["vms"]:\n',
    '                raise Fail("spec: empty or repeated vm line: %r" % line)\n',
    '            spec["vms"].append(name)\n',
    '            spec["set"].setdefault(name, [])\n',
    '        elif word == "host":\n',
    '            key, eq, value = rest.partition("=")\n',
    '            if not eq or not key.strip() or value == "":\n',
    '                raise Fail("spec: a host line needs </Section/Option>=<value>: %r" % line)\n',
    '            spec["host"].append((key.strip(), value))\n',
    '        elif word == "set":\n',
    '            name, _, kv = rest.partition(" ")\n',
    '            key, eq, value = kv.partition("=")\n',
    '            if not eq or not key.strip() or \'"\' in value:\n',
    '                raise Fail("spec: a set line needs <vm> <key>=<value> without double quotes: %r" % line)\n',
    '            if name not in spec["set"]:\n',
    '                raise Fail("spec: a set line names a VM that has no vm line: %r" % line)\n',
    '            spec["set"][name].append((key.strip(), value))\n',
    '        elif word == "off":\n',
    '            name = rest.strip()\n',
    '            if name not in spec["set"]:\n',
    '                raise Fail("spec: an off line names a VM that has no vm line: %r" % line)\n',
    '            if name not in spec["off"]:\n',
    '                spec["off"].append(name)\n',
    '        elif word == "opt":\n',
    '            key, _, value = rest.partition(" ")\n',
    '            try:\n',
    '                spec["opt"][key] = int(value)\n',
    '            except ValueError:\n',
    '                raise Fail("spec: the opt value is not a number: %r" % line)\n',
    '        else:\n',
    '            raise Fail("spec: unknown line: %r" % line)\n',
    '    if not spec["vms"] and not spec["host"]:\n',
    '        raise Fail("spec: nothing to do (no vm line and no host line)")\n',
    '    return spec\n',
    '\n',
    '\n',
    '# ---------------------------------------------------------------- VMs\n',
    'def all_vms():\n',
    '    rc, text = run(["vim-cmd", "vmsvc/getallvms"])\n',
    '    if rc != 0:\n',
    '        raise Fail("vim-cmd vmsvc/getallvms failed: %s" % short(text))\n',
    '    rows = []\n',
    '    for line in text.splitlines():\n',
    '        m = VM_ROW_RE.match(line)\n',
    '        if m:\n',
    '            rows.append({"id": m.group(1), "name": m.group(2).strip(), "ds": m.group(3), "file": m.group(4).strip()})\n',
    '    return rows\n',
    '\n',
    '\n',
    'def find_vm(rows, name):\n',
    '    hits = [r for r in rows if r["name"] == name]\n',
    '    if not hits:\n',
    '        raise Fail("VM \'%s\' is not registered on this host (vim-cmd vmsvc/getallvms). Nothing was changed." % name)\n',
    '    if len(hits) > 1:\n',
    '        raise Fail("the VM name \'%s\' is on %d lines of vim-cmd vmsvc/getallvms. Nothing was changed." % (name, len(hits)))\n',
    '    return hits[0]\n',
    '\n',
    '\n',
    'def vmx_path(row):\n',
    '    rc, text = run(["vim-cmd", "vmsvc/get.summary", row["id"]])\n',
    '    m = re.search(r\'vmPathName\\s*=\\s*"\\[([^\\]]+)\\]\\s*([^"]+)"\', text) if rc == 0 else None\n',
    '    ds, rel = (m.group(1), m.group(2)) if m else (row["ds"], row["file"])\n',
    '    path = os.path.join(VMFS_ROOT, ds, rel)\n',
    '    if not os.path.isfile(path):\n',
    '        raise Fail(".vmx file of VM \'%s\' not found: %s. Nothing was changed." % (row["name"], path))\n',
    '    return path\n',
    '\n',
    '\n',
    'def power_state(vmid):\n',
    '    rc, text = run(["vim-cmd", "vmsvc/power.getstate", vmid])\n',
    '    low = text.lower()\n',
    '    if rc == 0:\n',
    '        for word, state in (("powered on", "on"), ("powered off", "off"), ("suspended", "suspended")):\n',
    '            if word in low:\n',
    '                return state\n',
    '    raise Fail("cannot read the power state of vmid %s (vim-cmd vmsvc/power.getstate): %s" % (vmid, short(text)))\n',
    '\n',
    '\n',
    'def wait_state(vmid, want, seconds):\n',
    '    end = time.time() + seconds\n',
    '    while True:\n',
    '        if power_state(vmid) == want:\n',
    '            return True\n',
    '        if time.time() >= end:\n',
    '            return False\n',
    '        time.sleep(POLL)\n',
    '\n',
    '\n',
    'def hard_off(name, vmid):\n',
    '    rc, text = run(["vim-cmd", "vmsvc/power.off", vmid], timeout=300)\n',
    '    if not wait_state(vmid, "off", 5 if failed(rc, text) else 120):\n',
    '        raise Fail("VM \'%s\' did not power off (vim-cmd vmsvc/power.off: %s)" % (name, short(text)))\n',
    '\n',
    '\n',
    'def shut_down(vms, seconds):\n',
    '    """vms: [(name, vmid)] that are powered on. Ask every guest to shut down, wait, then power off what is still on."""\n',
    '    waiting = []\n',
    '    for name, vmid in vms:\n',
    '        rc, text = run(["vim-cmd", "vmsvc/power.shutdown", vmid])\n',
    '        if failed(rc, text):\n',
    '            out("  %s: guest shutdown is not possible (%s): power off" % (name, short(text)))\n',
    '            hard_off(name, vmid)\n',
    '        else:\n',
    '            out("  %s: guest shutdown requested" % name)\n',
    '            waiting.append((name, vmid))\n',
    '    end = time.time() + seconds\n',
    '    while waiting:\n',
    '        waiting = [(n, i) for n, i in waiting if power_state(i) != "off"]\n',
    '        if not waiting or time.time() >= end:\n',
    '            break\n',
    '        time.sleep(POLL)\n',
    '    for name, vmid in waiting:\n',
    '        out("  %s: still on %d s after the guest shutdown request: power off" % (name, seconds))\n',
    '        hard_off(name, vmid)\n',
    '    for name, vmid in vms:\n',
    '        if power_state(vmid) != "off":\n',
    '            raise Fail("VM \'%s\' is not powered off" % name)\n',
    '        out("  %s: powered off" % name)\n',
    '\n',
    '\n',
    '# ---------------------------------------------------------------- .vmx\n',
    'def read_vmx(path):\n',
    '    with open(path, "rb") as f:\n',
    '        return f.read().split(b"\\n")\n',
    '\n',
    '\n',
    'def key_of(raw):\n',
    '    m = LINE_RE.match(raw.decode("latin-1").rstrip("\\r"))\n',
    '    if not m:\n',
    '        return None, None\n',
    '    return m.group(1).lower(), (m.group(2) if m.group(2) is not None else m.group(3))\n',
    '\n',
    '\n',
    'def values_of(lines, key):\n',
    '    k = key.lower()\n',
    '    return [v for kk, v in (key_of(x) for x in lines) if kk == k]\n',
    '\n',
    '\n',
    'def same(values, want):\n',
    '    if want == "":\n',
    '        return not values\n',
    '    return len(values) == 1 and values[0] == want\n',
    '\n',
    '\n',
    'def show(values):\n',
    '    if not values:\n',
    '        return "(none)"\n',
    '    if len(values) == 1:\n',
    '        return \'"%s"\' % values[0]\n',
    '    return "%d lines: %s" % (len(values), ", ".join(\'"%s"\' % v for v in values))\n',
    '\n',
    '\n',
    'def edit_vmx(lines, items):\n',
    '    """Remove every line whose key is a wanted key (any letter case), then add one line per wanted value.\n',
    '    Every other line stays byte for byte."""\n',
    '    body = [x for x in lines if x.strip()]\n',
    '    eol = b"\\r" if body and all(x.endswith(b"\\r") for x in body) else b""\n',
    '    for key, want in items:\n',
    '        k = key.lower()\n',
    '        lines = [x for x in lines if key_of(x)[0] != k]\n',
    '        if want != "":\n',
    '            tail = []\n',
    '            while lines and lines[-1].strip() == b"":\n',
    '                tail.append(lines.pop())\n',
    '            lines.append((\'%s = "%s"\' % (key, want)).encode("ascii") + eol)\n',
    '            lines.extend(reversed(tail))\n',
    '    if not lines or lines[-1] != b"":\n',
    '        lines.append(b"")\n',
    '    return lines\n',
    '\n',
    '\n',
    'def replace_file(path, data):\n',
    '    tmp = path + ".tcgen-new"\n',
    '    with open(tmp, "wb") as f:\n',
    '        f.write(data)\n',
    '        f.flush()\n',
    '        os.fsync(f.fileno())\n',
    '    shutil.copymode(path, tmp)\n',
    '    os.rename(tmp, path)\n',
    '\n',
    '\n',
    'def write_vmx(path, lines, stamp):\n',
    '    backup = "%s.tcgen-%s" % (path, stamp)\n',
    '    shutil.copy2(path, backup)\n',
    '    replace_file(path, b"\\n".join(lines))\n',
    '    folder, base = os.path.dirname(path), os.path.basename(path)\n',
    '    old = sorted(n for n in os.listdir(folder) if re.match(re.escape(base) + r"\\.tcgen-\\d{14}$", n))\n',
    '    for n in old[:-KEEP_BACKUPS]:\n',
    '        try:\n',
    '            os.remove(os.path.join(folder, n))\n',
    '        except OSError:\n',
    '            pass\n',
    '    return backup\n',
    '\n',
    '\n',
    'def reload_vm(name, vmid):\n',
    '    rc, text = run(["vim-cmd", "vmsvc/reload", vmid])\n',
    '    if failed(rc, text):\n',
    '        raise Fail("vim-cmd vmsvc/reload failed for VM \'%s\': %s" % (name, short(text)))\n',
    '\n',
    '\n',
    '# ---------------------------------------------------------------- host options\n',
    'def host_get(path):\n',
    '    rc, text = run(["esxcli", "system", "settings", "advanced", "list", "-o", path])\n',
    '    if rc != 0:\n',
    '        raise Fail("host option \'%s\' cannot be read (esxcli system settings advanced list -o): %s. Nothing was changed."\n',
    '                   % (path, short(text)))\n',
    '    typ = re.search(r"^[ \\t]*Type:[ \\t]*(\\S+)", text, re.M)\n',
    '    if not typ or typ.group(1) not in ("integer", "string"):\n',
    '        raise Fail("host option \'%s\': the esxcli output has no known Type line. Nothing was changed." % path)\n',
    '    name = "Int Value" if typ.group(1) == "integer" else "String Value"\n',
    '    val = re.search(r"^[ \\t]*%s:[ \\t]*(.*)$" % name, text, re.M)\n',
    '    if not val:\n',
    '        raise Fail("host option \'%s\': the esxcli output has no \'%s\' line. Nothing was changed." % (path, name))\n',
    '    return typ.group(1), val.group(1).strip()\n',
    '\n',
    '\n',
    'def host_same(typ, cur, want):\n',
    '    if typ == "integer":\n',
    '        try:\n',
    '            return int(cur) == int(want)\n',
    '        except ValueError:\n',
    '            return False\n',
    '    return cur == want\n',
    '\n',
    '\n',
    'def host_set(path, typ, value):\n',
    '    flag = "-i" if typ == "integer" else "-s"\n',
    '    rc, text = run(["esxcli", "system", "settings", "advanced", "set", "-o", path, flag, value])\n',
    '    if rc != 0:\n',
    '        raise Fail("host option \'%s\' cannot be set to \'%s\' (esxcli system settings advanced set): %s" % (path, value, short(text)))\n',
    '    now = host_get(path)[1]\n',
    '    if not host_same(typ, now, value):\n',
    '        raise Fail("host option \'%s\' is \'%s\' after setting \'%s\'" % (path, now, value))\n',
    '\n',
    '\n',
    '# ---------------------------------------------------------------- analyse (reads only)\n',
    'def analyse(spec):\n',
    '    rows = all_vms() if spec["vms"] else []\n',
    '    found = [(name, find_vm(rows, name)) for name in spec["vms"]]      # every VM must exist before anything else\n',
    '    vms = []\n',
    '    changes = 0\n',
    '    for name, row in found:\n',
    '        path = vmx_path(row)\n',
    '        state = power_state(row["id"])\n',
    '        lines = read_vmx(path)\n',
    '        last = {}\n',
    '        order = []\n',
    '        for key, want in spec["set"][name]:\n',
    '            if key.lower() not in last:\n',
    '                order.append(key.lower())\n',
    '            last[key.lower()] = (key, want)          # the last line for a key wins\n',
    '        items = []\n',
    '        for k in order:\n',
    '            key, want = last[k]\n',
    '            cur = values_of(lines, key)\n',
    '            diff = not same(cur, want)\n',
    '            changes += 1 if diff else 0\n',
    '            items.append({"key": key, "want": want, "cur": cur, "diff": diff})\n',
    '        vms.append({"name": name, "id": row["id"], "vmx": path, "power": state, "items": items})\n',
    '    host = []\n',
    '    for path, want in spec["host"]:\n',
    '        typ, cur = host_get(path)\n',
    '        if typ == "integer":\n',
    '            try:\n',
    '                int(want)\n',
    '            except ValueError:\n',
    '                raise Fail("host option \'%s\' is an integer option, the wanted value is \'%s\'. Nothing was changed." % (path, want))\n',
    '        diff = not host_same(typ, cur, want)\n',
    '        changes += 1 if diff else 0\n',
    '        host.append({"path": path, "type": typ, "cur": cur, "want": want, "diff": diff})\n',
    '    for v in vms:\n',
    '        out("TCGEN-VM %s vmid=%s power=%s vmx=%s" % (v["name"], v["id"], v["power"], v["vmx"]))\n',
    '        for it in v["items"]:\n',
    '            out("TCGEN-SET %s %s: %s -> %s  [%s]" % (v["name"], it["key"], show(it["cur"]),\n',
    '                                                     (\'"%s"\' % it["want"]) if it["want"] != "" else "(remove)",\n',
    '                                                     "change" if it["diff"] else "same"))\n',
    '    for h in host:\n',
    '        out("TCGEN-HOST %s (%s): %s -> %s  [%s]" % (h["path"], h["type"], h["cur"], h["want"],\n',
    '                                                   "change" if h["diff"] else "same"))\n',
    '    bad = [v["name"] for v in vms if v["power"] == "suspended"]\n',
    '    if bad:\n',
    '        raise Fail("suspended VM: %s. Resume it or power it off first. Nothing was changed." % ", ".join(bad))\n',
    '    return vms, host, changes\n',
    '\n',
    '\n',
    '# ---------------------------------------------------------------- state for rollback\n',
    'def state_path(tag):\n',
    '    if not re.match(r"^[A-Za-z0-9._-]+$", tag or ""):\n',
    '        raise Fail("bad tag: %r" % tag)\n',
    '    return os.path.join(TMP, "state-%s.json" % tag)\n',
    '\n',
    '\n',
    'def save_state(tag, state):\n',
    '    tmp = state_path(tag) + ".new"\n',
    '    with open(tmp, "w") as f:\n',
    '        json.dump(state, f)\n',
    '    os.rename(tmp, state_path(tag))\n',
    '\n',
    '\n',
    '# ---------------------------------------------------------------- commands\n',
    'def cmd_check(spec):\n',
    '    vms, host, changes = analyse(spec)\n',
    '    pon = poff = 0\n',
    '    for v in vms:\n',
    '        want = "off" if v["name"] in spec["off"] else "on"\n',
    '        if want == "on" and v["power"] != "on":\n',
    '            pon += 1\n',
    '        if want == "off" and v["power"] != "off":\n',
    '            poff += 1\n',
    '        out("TCGEN-POWER %s now=%s want=%s  [%s]" % (v["name"], v["power"], want, "same" if v["power"] == want else "change"))\n',
    '    parts = (["%d value(s) differ" % changes] if changes else []) + (["%d VM(s) to power on" % pon] if pon else []) + \\\n',
    '        (["%d VM(s) to power off" % poff] if poff else [])\n',
    '    if parts:\n',
    '        result("wouldchange", ", ".join(parts))\n',
    '    else:\n',
    '        result("nochange")\n',
    '\n',
    '\n',
    'def cmd_prepare(tag, spec):\n',
    '    state_path(tag)\n',
    '    vms, host, changes = analyse(spec)\n',
    '    if not changes:\n',
    '        result("nochange")\n',
    '        return\n',
    '    stamp = time.strftime("%Y%m%d%H%M%S")\n',
    '    wait = spec["opt"]["shutdown_wait"]\n',
    '    state = {"tag": tag, "shutdown_wait": wait, "was_on": [v["name"] for v in vms if v["power"] == "on"],\n',
    '             "vms": [], "host": []}\n',
    '    save_state(tag, state)\n',
    '    if state["was_on"]:\n',
    '        out("shutting down the VMs of this case: %s" % ", ".join(state["was_on"]))\n',
    '        shut_down([(v["name"], v["id"]) for v in vms if v["power"] == "on"], wait)\n',
    '    for h in host:\n',
    '        if not h["diff"]:\n',
    '            continue\n',
    '        state["host"].append({"path": h["path"], "type": h["type"], "old": h["cur"]})\n',
    '        save_state(tag, state)\n',
    '        host_set(h["path"], h["type"], h["want"])\n',
    '        out("TCGEN-DONE host %s: %s -> %s" % (h["path"], h["cur"], h["want"]))\n',
    '    for v in vms:\n',
    '        todo = [(it["key"], it["want"]) for it in v["items"] if it["diff"]]\n',
    '        if not todo:\n',
    '            continue\n',
    '        backup = "%s.tcgen-%s" % (v["vmx"], stamp)\n',
    '        state["vms"].append({"name": v["name"], "id": v["id"], "vmx": v["vmx"], "backup": backup})\n',
    '        save_state(tag, state)\n',
    '        write_vmx(v["vmx"], edit_vmx(read_vmx(v["vmx"]), todo), stamp)\n',
    '        reload_vm(v["name"], v["id"])\n',
    '        lines = read_vmx(v["vmx"])\n',
    '        wrong = [k for k, w in todo if not same(values_of(lines, k), w)]\n',
    '        if wrong:\n',
    '            raise Fail("VM \'%s\': the .vmx does not hold the wanted value after writing: %s" % (v["name"], ", ".join(wrong)))\n',
    '        out("TCGEN-DONE vm %s: %d key(s) written, reloaded. backup %s" % (v["name"], len(todo), backup))\n',
    '    result("changed", "%d value(s)" % changes)\n',
    '\n',
    '\n',
    'def cmd_poweron(name, seconds):\n',
    '    row = find_vm(all_vms(), name)\n',
    '    if power_state(row["id"]) == "on":\n',
    '        out("%s: already powered on" % name)\n',
    '        result("alreadyon")\n',
    '        return\n',
    '    begin = time.time()\n',
    '    try:\n',
    '        rc, text = run(["vim-cmd", "vmsvc/power.on", row["id"]], timeout=seconds)\n',
    '    except NoAnswer:\n',
    '        # vim-cmd only asks hostd for the power-on task and waits for it. Ending vim-cmd does not end the task.\n',
    '        if power_state(row["id"]) == "on":\n',
    '            out("%s: powered on (vim-cmd vmsvc/power.on did not return within %d s, the state is \'Powered on\')" % (name, seconds))\n',
    '            result("poweredon")\n',
    '            return\n',
    '        raise Fail("VM \'%s\' is not \'Powered on\' %d s after vim-cmd vmsvc/power.on was started. "\n',
    '                   "The power-on task may still be running on the host." % (name, seconds))\n',
    '    if failed(rc, text):\n',
    '        raise Fail("VM \'%s\' did not power on (vim-cmd vmsvc/power.on): %s" % (name, short(text)))\n',
    '    if not wait_state(row["id"], "on", 120):\n',
    '        raise Fail("VM \'%s\' is not \'Powered on\' after vim-cmd vmsvc/power.on" % name)\n',
    '    out("%s: powered on (vim-cmd vmsvc/power.on took %d s)" % (name, int(time.time() - begin)))\n',
    '    result("poweredon")\n',
    '\n',
    '\n',
    'def cmd_poweroff(name, seconds):\n',
    '    row = find_vm(all_vms(), name)\n',
    '    state = power_state(row["id"])\n',
    '    if state == "off":\n',
    '        out("%s: already powered off" % name)\n',
    '        result("alreadyoff")\n',
    '        return\n',
    '    if state == "suspended":\n',
    '        raise Fail("VM \'%s\' is suspended. Resume it or power it off first." % name)\n',
    '    shut_down([(name, row["id"])], seconds)\n',
    '    result("poweredoff")\n',
    '\n',
    '\n',
    'LPAGE = "/memory/lpage/vmLpage"\n',
    '\n',
    '\n',
    'def lpage_ids(name):\n',
    '    """World ID and VMX Cartel ID of a running VM (esxcli vm process list), in that order."""\n',
    '    rc, text = run(["esxcli", "vm", "process", "list"])\n',
    '    if rc != 0:\n',
    '        return []\n',
    '    blocks, cur = [], {}\n',
    '    for line in text.splitlines():\n',
    '        if line.strip() and not line[:1].isspace():\n',
    '            if cur:\n',
    '                blocks.append(cur)\n',
    '            cur = {}\n',
    '            continue\n',
    '        key, sep, value = line.strip().partition(":")\n',
    '        if sep:\n',
    '            cur[key.strip()] = value.strip()\n',
    '    if cur:\n',
    '        blocks.append(cur)\n',
    '    for b in blocks:\n',
    '        if b.get("Display Name") == name:\n',
    '            return [x for x in (b.get("World ID"), b.get("VMX Cartel ID")) if x and x.isdigit()]\n',
    '    return []\n',
    '\n',
    '\n',
    'LPAGE_POLL = float(os.environ.get("TCGEN_LPAGE_POLL_SEC", "15"))   # seconds between two readings\n',
    'LPAGE_EVERY = 15        # seconds of the time limit that one reading stands for\n',
    'LPAGE_STALL = 6         # readings in a row without an increase: the backing has stopped\n',
    'LPAGE_NONODE = 8        # readings in a row without a vsish node (about 2 min): the backing cannot be read\n',
    '\n',
    '\n',
    'def lpage_read(name):\n',
    '    """One reading of the 1GB page backing: (state, current, target, failed).\n',
    '    state: off (1GB pages not set in the .vmx), poweredoff, nonode (no readable vsish node), ok."""\n',
    '    row = find_vm(all_vms(), name)\n',
    '    lines = read_vmx(vmx_path(row))\n',
    '    on = values_of(lines, "sched.mem.lpage.enable1GPage")\n',
    '    if not (len(on) == 1 and on[0].strip().upper() == "TRUE"):\n',
    '        return "off", 0, 0, 0\n',
    '    mem = values_of(lines, "memSize")\n',
    '    try:\n',
    '        target = int(mem[-1]) // 1024\n',
    '    except (IndexError, ValueError):\n',
    '        raise Fail("VM \'%s\': memSize of the .vmx is not a number: %s" % (name, show(mem)))\n',
    '    if power_state(row["id"]) != "on":\n',
    '        return "poweredoff", 0, target, 0\n',
    '    rc, listed = run(["vsish", "-e", "ls", LPAGE + "/"])\n',
    '    have = set(x.strip().strip("/") for x in listed.splitlines()) if rc == 0 else set()\n',
    '    ids = lpage_ids(name)\n',
    '    for vid in [i for i in ids if i in have] + [i for i in ids if i not in have]:\n',
    '        rc, text = run(["vsish", "-e", "get", "%s/%s" % (LPAGE, vid)])\n',
    '        cur = re.search(r"Current number of 1GB page backings\\s*:\\s*(\\d+)", text, re.I) if rc == 0 else None\n',
    '        if not cur:\n',
    '            continue\n',
    '        failed = re.search(r"1GB page backing attempts failed\\s*:\\s*(\\d+)", text, re.I)\n',
    '        return "ok", int(cur.group(1)), target, int(failed.group(1)) if failed else 0\n',
    '    return "nonode", 0, target, 0\n',
    '\n',
    '\n',
    'def cmd_lpage(name):\n',
    '    """1GB page backing of a VM: TCGEN-LPAGE <current> <target> <failed>, or off (1GB pages not set), poweredoff, nonode."""\n',
    '    state, n, target, f = lpage_read(name)\n',
    '    text = ("%d %d %d" % (n, target, f)) if state == "ok" else state\n',
    '    out("TCGEN-LPAGE " + text)\n',
    '    result("lpage", text)\n',
    '\n',
    '\n',
    '# ---------------------------------------------------------------- configuration snapshot (read only)\n',
    '# The items and their names are those of the VM table of config_snapshot (VM basic information, vm advanced config,\n',
    '# CPU affinity). Here they are read from the .vmx file: that is the place where the settings of tcgen (set lines) go.\n',
    'SNAP_ADV_KEYS = ("sched.mem.lpage.enable1GPage", "sched.mem.pin", "sched.mem.prealloc", "sched.mem.prealloc.pinnedMainMem",\n',
    '                 "sched.swap.vmxSwapEnabled", "numa.vcpu.preferHT", "numa.vcpu.maxPerVirtualNode",\n',
    '                 "monitor_control.halt_in_monitor", "monitor.idleLoopSpinBeforeHalt", "monitor.idleLoopMinSpinUS",\n',
    '                 "monitor_control.disable_pause_loop_exiting", "vpmc.enable")\n',
    'SNAP_BASIC_KEYS = ("numvcpus", "cpuid.corespersocket", "memsize", "sched.mem.min", "sched.cpu.shares", "sched.mem.shares",\n',
    '                   "sched.cpu.latencysensitivity")\n',
    'SNAP_AFF_FIXED = ("sched.cpu.affinity", "numa.nodeAffinity")\n',
    'SNAP_AFF_RE = re.compile(r"^sched\\.(vcpu|node)(\\d+)\\.affinity$")\n',
    '\n',
    '\n',
    'def read_snap_spec(data):\n',
    '    vms, keys = [], []\n',
    '    for raw in data.decode("ascii", "replace").split("\\n"):\n',
    '        line = raw.rstrip("\\r").strip()\n',
    '        if not line or line.startswith("#"):\n',
    '            continue\n',
    '        word, _, rest = line.partition(" ")\n',
    '        rest = rest.strip()\n',
    '        if word == "vm" and rest:\n',
    '            if rest not in vms:\n',
    '                vms.append(rest)\n',
    '        elif word == "key" and rest:\n',
    '            if rest.lower() not in [k.lower() for k in keys]:\n',
    '                keys.append(rest)\n',
    '        else:\n',
    '            raise Fail("snapshot spec: unknown line: %r" % line)\n',
    '    if not vms:\n',
    '        raise Fail("snapshot spec: no vm line")\n',
    '    return vms, keys\n',
    '\n',
    '\n',
    'def snap_number(values):\n',
    '    try:\n',
    '        return int(values[0]) if len(values) == 1 else None\n',
    '    except ValueError:\n',
    '        return None\n',
    '\n',
    '\n',
    'def snap_vm(name, lines, state, keys):\n',
    '    """The snapshot rows of one VM: a list of (group, item, value). An empty value: the .vmx has no such key."""\n',
    '    def one(key):\n',
    '        return " | ".join(values_of(lines, key))\n',
    '\n',
    '    rows = [("basic", "power state", state)]\n',
    '    cpu = snap_number(values_of(lines, "numvcpus")) or 1            # no numvcpus line: 1 vCPU\n',
    '    cps = snap_number(values_of(lines, "cpuid.coresPerSocket")) or 1\n',
    '    rows.append(("basic", "cpu", str(cpu)))\n',
    '    rows.append(("basic", "cores per socket / sockets", "%d / %s" % (cps, (cpu // cps) if cpu % cps == 0 else "?")))\n',
    '    mem = snap_number(values_of(lines, "memSize"))\n',
    '    if mem is None:\n',
    '        rows.append(("basic", "memory (GB)", one("memSize")))\n',
    '    else:\n',
    '        rows.append(("basic", "memory (GB)", str(mem // 1024) if mem % 1024 == 0 else "%.1f" % (mem / 1024.0)))\n',
    '    res = one("sched.mem.min")\n',
    '    rows.append(("basic", "memory reservation", (res + " MB") if res else ""))\n',
    '    rows.append(("basic", "cpu shares", one("sched.cpu.shares")))\n',
    '    rows.append(("basic", "mem shares", one("sched.mem.shares")))\n',
    '    rows.append(("basic", "latency sensitivity", one("sched.cpu.latencySensitivity")))\n',
    '    skip = set(SNAP_BASIC_KEYS) | set(k.lower() for k in SNAP_AFF_FIXED)\n',
    '    done = set()\n',
    '    for key in list(SNAP_ADV_KEYS) + list(keys):\n',
    '        low = key.lower()\n',
    '        if low in skip or low in done or SNAP_AFF_RE.match(low):\n',
    '            continue\n',
    '        done.add(low)\n',
    '        rows.append(("adv", key, one(key)))\n',
    '    found = {}\n',
    '    for raw in lines:\n',
    '        k, v = key_of(raw)\n',
    '        m = SNAP_AFF_RE.match(k) if k else None\n',
    '        if m:\n',
    '            found[(0 if m.group(1) == "vcpu" else 1, int(m.group(2)))] = k\n',
    '    rows.append(("aff", SNAP_AFF_FIXED[0], one(SNAP_AFF_FIXED[0])))\n',
    '    for _, k in sorted(found.items()):\n',
    '        rows.append(("aff", k, one(k)))\n',
    '    rows.append(("aff", SNAP_AFF_FIXED[1], one(SNAP_AFF_FIXED[1])))\n',
    '    return rows\n',
    '\n',
    '\n',
    'def cmd_snapshot(vms, keys):\n',
    '    """Read only: the settings of each VM as lines TCGEN-CFG <vm>|<group>|<item>|<value>."""\n',
    '    table = all_vms()\n',
    '    n = 0\n',
    '    for name in vms:\n',
    '        try:\n',
    '            row = find_vm(table, name)\n',
    '            lines = read_vmx(vmx_path(row))\n',
    '            state = power_state(row["id"])\n',
    '        except Fail as e:\n',
    '            out("vm %s: settings not read: %s" % (name, e))\n',
    '            out("TCGEN-CFG %s|basic|power state|not read" % name)\n',
    '            continue\n',
    '        for group, item, value in snap_vm(name, lines, state, keys):\n',
    '            out("TCGEN-CFG %s|%s|%s|%s" % (name, group, item, value.replace("\\t", " ")))\n',
    '        n += 1\n',
    '    result("snapshot", "%d of %d VM(s) read" % (n, len(vms)))\n',
    '\n',
    '\n',
    'def cmd_lpagewait(name, seconds):\n',
    '    """Wait until the 1GB page backing of a powered-on VM is complete. Result "lpage <state> [current target failed]":\n',
    '    complete, off (1GB pages not set: nothing to wait for), nonode, stalled (no increase, no failed attempts),\n',
    '    failed (no increase and failed attempts > 0: the host has no free contiguous 1GB memory), timeout, poweredoff."""\n',
    '    tries = max(1, int(seconds) // LPAGE_EVERY)\n',
    '    prev, stall, nonode, shown = -1, 0, 0, None\n',
    '    state, n, target, f = "nonode", 0, 0, 0\n',
    '    begin = time.time()\n',
    '    for i in range(tries):\n',
    '        if i:\n',
    '            time.sleep(LPAGE_POLL)\n',
    '        state, n, target, f = lpage_read(name)\n',
    '        if state in ("off", "poweredoff"):\n',
    '            out("TCGEN-LPAGE " + state)\n',
    '            result("lpage", state)\n',
    '            return\n',
    '        if state == "nonode":\n',
    '            nonode += 1\n',
    '            if nonode >= LPAGE_NONODE:\n',
    '                out("TCGEN-LPAGE nonode")\n',
    '                result("lpage", "nonode")\n',
    '                return\n',
    '            continue\n',
    '        nonode = 0\n',
    '        line = "TCGEN-LPAGE %d %d %d" % (n, target, f)\n',
    '        if line != shown:                       # one line for every change, not for every reading\n',
    '            out("%s  (%d s)" % (line, int(time.time() - begin)))\n',
    '            shown = line\n',
    '        if n >= target:\n',
    '            result("lpage", "complete %d %d %d" % (n, target, f))\n',
    '            return\n',
    '        stall = stall + 1 if (prev >= 0 and n <= prev) else 0\n',
    '        if stall >= LPAGE_STALL:\n',
    '            result("lpage", "%s %d %d %d" % ("failed" if f > 0 else "stalled", n, target, f))\n',
    '            return\n',
    '        prev = n\n',
    '    if state == "nonode":\n',
    '        out("TCGEN-LPAGE nonode")\n',
    '        result("lpage", "nonode")\n',
    '        return\n',
    '    result("lpage", "timeout %d %d %d" % (n, target, f))\n',
    '\n',
    '\n',
    'def cmd_rollback(tag):\n',
    '    path = state_path(tag)\n',
    '    if not os.path.isfile(path):\n',
    '        result("nothing", "no change is recorded for tag %s" % tag)\n',
    '        return\n',
    '    with open(path) as f:\n',
    '        state = json.load(f)\n',
    '    for name in state.get("was_on", []):\n',
    '        out("TCGEN-WASON %s" % name)\n',
    '    rows = all_vms() if state["vms"] else []\n',
    '    for v in state["vms"]:\n',
    '        if not os.path.isfile(v["backup"]):\n',
    '            continue                              # prepare ended before this .vmx was written\n',
    '        row = find_vm(rows, v["name"])\n',
    '        if power_state(row["id"]) != "off":\n',
    '            out("%s: powering off before the .vmx is put back" % v["name"])\n',
    '            shut_down([(v["name"], row["id"])], int(state.get("shutdown_wait", 600)))\n',
    '        with open(v["backup"], "rb") as f:\n',
    '            data = f.read()\n',
    '        replace_file(v["vmx"], data)\n',
    '        reload_vm(v["name"], row["id"])\n',
    '        out("TCGEN-DONE vm %s: .vmx put back from %s" % (v["name"], v["backup"]))\n',
    '    for h in state["host"]:\n',
    '        host_set(h["path"], h["type"], h["old"])\n',
    '        out("TCGEN-DONE host %s: put back to %s" % (h["path"], h["old"]))\n',
    '    os.rename(path, path + ".rolledback")\n',
    '    result("rolledback", "%d VM(s), %d host option(s)" % (len(state["vms"]), len(state["host"])))\n',
    '\n',
    '\n',
    'def main(argv):\n',
    '    lock = None\n',
    '    try:\n',
    '        try:\n',
    '            signal.signal(signal.SIGHUP, signal.SIG_IGN)\n',
    '        except (AttributeError, ValueError, OSError):\n',
    '            pass\n',
    '        if len(argv) >= 2 and argv[1] == "version":\n',
    '            sys.stdout.write(VERSION + "\\n")\n',
    '            return 0\n',
    '        if len(argv) == 2 and argv[1] == "check":\n',
    '            cmd_check(read_spec(sys.stdin.buffer.read()))\n',
    '        elif len(argv) == 3 and argv[1] == "prepare":\n',
    '            spec = read_spec(sys.stdin.buffer.read())\n',
    '            lock = take_lock()\n',
    '            cmd_prepare(argv[2], spec)\n',
    '        elif len(argv) in (3, 4) and argv[1] == "poweron":\n',
    '            lock = take_lock()\n',
    '            cmd_poweron(argv[2], int(argv[3]) if len(argv) == 4 else POWERON_WAIT)\n',
    '        elif len(argv) == 3 and argv[1] == "rollback":\n',
    '            lock = take_lock()\n',
    '            cmd_rollback(argv[2])\n',
    '        elif len(argv) in (3, 4) and argv[1] == "poweroff":\n',
    '            lock = take_lock()\n',
    '            cmd_poweroff(argv[2], int(argv[3]) if len(argv) == 4 else 600)\n',
    '        elif len(argv) == 3 and argv[1] == "lpage":\n',
    '            cmd_lpage(argv[2])\n',
    '        elif len(argv) in (3, 4) and argv[1] == "lpagewait":\n',
    '            cmd_lpagewait(argv[2], int(argv[3]) if len(argv) == 4 else POWERON_WAIT)\n',
