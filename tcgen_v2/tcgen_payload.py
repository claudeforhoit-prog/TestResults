    '      return 1\n',
    '    fi\n',
    '    register_part\n',
    '    if [ -n "$TAKE" ]; then\n',
    '      if [ -n "$RC_W" ] && [ "$(now)" -lt "$RC_W" ]; then\n',
    '        STEP=wait-cleanup\n',
    '        setstate running "waiting until $(tstr "$RC_W") to remove the crontab lines that run(s) $(say $TAKE) left${AT:+ ($PREP min before the job start $ATTEXT of case $CNAME)}"\n',
    '        if ! wait_until "$RC_W"; then\n',
    '          stopped "before the crontab lines that run(s) $(say $TAKE) left were removed. The crontab lines of this run stay registered: its jobs start at their times. To remove them: sh $D/tcrun cancel $CHF"\n',
    '          return 1\n',
    '        fi\n',
    '      fi\n',
    '      take_over\n',
    '    fi\n',
    '  fi\n',
    '  if [ -z "$JOBVMS" ]; then\n',
    '    R_STATUS="done (settings only)"; write_result\n',
    '    log "==== case $CNAME done (settings only, no job)"\n',
    '    return 0\n',
    '  fi\n',
    '  TJOB=$((AT / 60 * 60))\n',
    '  R_JOB=$(tstr "$TJOB")\n',
    '  if [ "$HASMON" = 1 ]; then                      # the monitoring start that was registered (times: case, first start, job start)\n',
    '    RC_M=$(grep "^$SEQ " "$W/times" 2>/dev/null | head -n 1 | cut -d\' \' -f2)\n',
    '    case "$RC_M" in ""|*[!0-9]*) RC_M=$((TJOB - LEAD * 60)) ;; esac\n',
    '    R_MON=$(tstr "$RC_M")\n',
    '  fi\n',
    '  [ -n "$MSTOP" ] && R_STOP=$(tstr "$MSTOP")\n',
    '  if ! grep -qx "$SEQ" "$W/reg.ok" 2>/dev/null; then\n',
    '    R_JOB=; R_MON=; R_STOP=\n',
    '    R_STATUS="not registered"; write_result\n',
    '    log "==== case $CNAME done: NOT registered (see the WARN line above and $JOBS)"\n',
    '    return 0\n',
    '  fi\n',
    '  # config snapshot: SNAPLEAD min before the job start of every case (user decision 2026-11-18)\n',
    '  if [ -n "$VMS" ]; then\n',
    '    RC_S=$((TJOB - SNAPLEAD * 60))\n',
    '    if [ "$(now)" -lt "$RC_S" ]; then\n',
    '      STEP=wait-snapshot\n',
    '      setstate running "waiting until $(tstr "$RC_S") to take the config snapshot of case $CNAME ($SNAPLEAD min before the job start $ATTEXT)"\n',
    '      if ! wait_until "$RC_S"; then\n',
    '        stopped "before the config snapshot of case $CNAME. Its crontab lines stay registered: the job starts at $ATTEXT. To remove them: sh $D/tcrun cancel $CHF"\n',
    '        return 1\n',
    '      fi\n',
    '    fi\n',
    '    if [ "$(now)" -ge $((TJOB - 60)) ]; then\n',
    '      log "WARN config snapshot of case $CNAME not taken: the job start $ATTEXT is less than 1 min away or has passed (no login to the VMs while a job runs)"\n',
    '    else\n',
    '      SN_WHY="before the job of this case"\n',
    '      [ "$R_APPLY" = changed ] && SN_WHY="$SN_WHY. Settings changed by this case"\n',
    '      [ -n "$PV_NEW" ] && SN_WHY="$SN_WHY. Powered on by this case:$PV_NEW"\n',
    '      [ -n "$PV_OFFED" ] && SN_WHY="$SN_WHY. Powered off by this case:$PV_OFFED"\n',
    '      snapshot\n',
    '    fi\n',
    '  fi\n',
    '  R_STATUS=registered; write_result; write_report\n',
    '  log "==== case $CNAME done. job start $R_JOB (crontab)"\n',
    '  return 0\n',
    '}\n',
    '\n',
    'on_signal() {       # the runner is ended by a signal (sh tcrun cancel sends TERM). The login that runs is ended, and the\n',
    '                    # registration record gets rows for the cases that were not registered\n',
    '  [ -n "$G_P" ] && kill "$G_P" 2>/dev/null\n',
    '  log "ended by a signal"\n',
    '  OS_C=$CNAME\n',
    '  HOW=stopped; HOW_TEXT="ended by a signal"\n',
    '  if [ -f "$RD/$CHF.cancelling" ]; then HOW=cancelled; HOW_TEXT="sh tcrun cancel"; fi\n',
