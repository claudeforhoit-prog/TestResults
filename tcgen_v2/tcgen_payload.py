    '    say "==== tcrun $TCRUN_VERSION, plan made by tcgen $PVER: paste block A again. Nothing started."\n',
    '    exit 3\n',
    '  fi\n',
    '  for CS_X in askpass esxssh tcgen_apply.py; do\n',
