    '    PV_STOPPABLE=\n',
    '    if [ "$PV_X" != 0 ]; then\n',
    '      if [ -n "$PO_STOP" ]; then power_stopped "$WHY"; else power_fail "$WHY"; fi\n',
    '      return 1\n',
    '    fi\n',
    '    [ "$PO_NEW" = 1 ] && PV_NEW="$PV_NEW $PV_VM"\n',
    '  done\n',
    '  if [ -n "$PV_NEW" ]; then\n',
    '    log "VM power: done. Powered on by this case:$PV_NEW. The last one was ready at $(tstr "$PO_READY")"\n',
    '  else\n',
    '    log "VM power: done. Every VM was on already"\n',
    '  fi\n',
    '  return 0\n',
    '}\n',
    '\n',
    '# ---------------------------------------------------------------- step 2 and 3: clocks and crontab lines\n',
    'last_on() {         # T_ON = when the VMs of this case were last powered on again by this run (empty: never)\n',
    '  T_ON=; R_VMSON=\n',
    '  for LO_VM in $VMS; do\n',
    '    LO_T=$(cat "$W/on.$LO_VM" 2>/dev/null)\n',
    '    case "$LO_T" in ""|*[!0-9]*) continue ;; esac\n',
    '    [ -z "$T_ON" ] || [ "$LO_T" -gt "$T_ON" ] && T_ON=$LO_T\n',
    '  done\n',
    '  [ -n "$T_ON" ] && R_VMSON=$(tstr "$T_ON")\n',
    '  return 0\n',
    '}\n',
    'probe_clocks() {    # OFF = how far the latest clock is ahead of this machine (>= 0), MINOFF = the smallest lead\n',
    '  PC_MAX=; PC_MIN=; PC_VMAX=; PC_VMIN=\n',
    '  mk_probe "$W/probe.sh"\n',
    '  for PC_VM in $REGVMS; do\n',
    '    PC_J=$(now)\n',
    '    vmrun "$(target "$PC_VM")" "$W/probe.sh" "$W/probe.out" 60\n',
    '    PC_R=$?\n',
    '    PC_C=$(tval TCGEN-CLOCK "$W/probe.out")\n',
    '    case "$PC_C" in\n',
    '      ""|*[!0-9]*) WHY="vm $PC_VM: ssh login failed (exit $PC_R: $(first "$W/probe.out"))"; return 1 ;;\n',
    '    esac\n',
    '    if [ "$(tval TCGEN-CRONTAB "$W/probe.out")" != yes ]; then WHY="vm $PC_VM: crontab command not found"; return 1; fi\n',
    '    if [ -z "$NOCHK" ] && vhas JOB "$PC_VM" && [ "$(tval TCGEN-PGREP "$W/probe.out")" != yes ]; then\n',
    '      WHY="vm $PC_VM: pgrep not found, the end of the job cannot be detected"\n',
    '      return 1\n',
    '    fi\n',
    '    PC_O=$((PC_C - PC_J))\n',
    '    [ -z "$PC_MAX" ] || [ "$PC_O" -gt "$PC_MAX" ] && PC_MAX=$PC_O\n',
    '    [ -z "$PC_MIN" ] || [ "$PC_O" -lt "$PC_MIN" ] && PC_MIN=$PC_O\n',
    '    [ -z "$PC_VMAX" ] || [ "$PC_O" -gt "$PC_VMAX" ] && PC_VMAX=$PC_O\n',
    '    [ -z "$PC_VMIN" ] || [ "$PC_O" -lt "$PC_VMIN" ] && PC_VMIN=$PC_O\n',
    '    log "clock: vm $PC_VM is $PC_O s ahead of the jump VM (negative: behind)"\n',
    '  done\n',
    '  if has EMS || has EMX; then\n',
    '    say \'echo "TCGEN-CLOCK `date +%s`"\' > "$W/eclock.sh"\n',
    '    PC_J=$(now)\n',
    '    esxrun "$W/eclock.sh" "$W/eclock.out" 60\n',
    '    PC_R=$?\n',
    '    PC_C=$(tval TCGEN-CLOCK "$W/eclock.out")\n',
    '    case "$PC_C" in\n',
    '      ""|*[!0-9]*) WHY="esx $CHF: ssh key login failed (exit $PC_R: $(first "$W/eclock.out"))"; return 1 ;;\n',
    '    esac\n',
    '    PC_O=$((PC_C - PC_J))\n',
    '    [ -z "$PC_MAX" ] || [ "$PC_O" -gt "$PC_MAX" ] && PC_MAX=$PC_O\n',
    '    [ -z "$PC_MIN" ] || [ "$PC_O" -lt "$PC_MIN" ] && PC_MIN=$PC_O\n',
    '    log "clock: esx $CHF is $PC_O s ahead of the jump VM (negative: behind)"\n',
    '  fi\n',
    '  OFF=${PC_MAX:-0}; MINOFF=${PC_MIN:-0}\n',
    '  [ "$OFF" -lt 0 ] && OFF=0\n',
    '  if [ -n "$PC_VMAX" ] && [ $((PC_VMAX - PC_VMIN)) -gt 30 ]; then\n',
    '    log "WARN the clocks of the VMs differ by $((PC_VMAX - PC_VMIN)) s. The jobs start that far apart. Check time sync."\n',
    '  fi\n',
    '  return 0\n',
    '}\n',
    'unregister() {      # remove the lines of this case from every VM and from the ESX host\n',
    '  for UR_VM in $REGVMS; do\n',
    '    mk_vmcron "$UR_VM" "$W/unreg.sh"\n',
    '    vmrun "$(target "$UR_VM")" "$W/unreg.sh" "$W/unreg.out" 60\n',
    '    if [ "$(tval TCGEN-CRON "$W/unreg.out")" = ok ]; then\n',
    '      log "removed the lines of this case: vm $UR_VM"\n',
    '    else\n',
    '      log "WARN the lines of this case could not be removed on vm $UR_VM ($(first "$W/unreg.out"))"\n',
    '    fi\n',
    '  done\n',
    '  if has EPAT; then\n',
    '    mk_esxcron "$W/eunreg.sh"\n',
    '    esxrun "$W/eunreg.sh" "$W/eunreg.out" 60\n',
    '    if [ "$(tval TCGEN-CRON "$W/eunreg.out")" = ok ]; then\n',
    '      log "removed the lines of this case: esx $CHF"\n',
    '    else\n',
    '      log "WARN the lines of this case could not be removed on esx $CHF ($(first "$W/eunreg.out"))"\n',
    '    fi\n',
    '  fi\n',
    '}\n',
    'ahead() {           # seconds from now to the earliest start time: 75, and 4 more for every host beyond four\n',
    '  AH_N=$(say "$REGVMS" | grep -c .)\n',
    '  has EPAT && AH_N=$((AH_N + 1))\n',
    '  if [ "$AH_N" -gt 4 ]; then say $((75 + 4 * (AH_N - 4))); else say 75; fi\n',
    '}\n',
    'register() {\n',
    '  STEP=register\n',
    '  RG_TRY=0\n',
    '  RG_AHEAD=$(ahead)\n',
    '  while :; do\n',
    '    RG_TRY=$((RG_TRY + 1))\n',
    '    setstate running "reading clocks and registering crontab lines (try $RG_TRY)"\n',
    '    if ! probe_clocks; then\n',
    '      [ "$RG_TRY" -gt 1 ] && unregister\n',
    '      pause "$WHY. Nothing of case $CNAME was started."\n',
    '      return 1\n',
    '    fi\n',
    '    RG_T=$(( ($(now) + OFF + RG_AHEAD + 59) / 60 * 60 ))\n',
    '    RG_L=0\n',
    '    [ "$HASMON" = 1 ] && RG_L=$((LEAD * 60))\n',
    '    if [ -n "$T_ON" ] && [ "$SETTLE" -gt 0 ]; then\n',
    '      # VMs of this case were powered on again by this run: the job must not start before T_ON + SETTLE min\n',
    '      RG_S=$(( (T_ON + OFF + SETTLE * 60 - RG_L + 59) / 60 * 60 ))\n',
    '      if [ "$RG_S" -gt "$RG_T" ]; then\n',
    '        log "settle: VMs of this case were powered on again (finished $R_VMSON). The job must start $SETTLE min or more after that: first start time moved from $(tstr "$RG_T") to $(tstr "$RG_S")"\n',
    '        RG_T=$RG_S\n',
    '      elif [ "$RG_TRY" = 1 ]; then\n',
    '        log "settle: VMs of this case were powered on again (finished $R_VMSON). The job start is already $SETTLE min or more after that: no extra wait"\n',
    '      fi\n',
    '    fi\n',
    '    if [ -z "$AT" ] && [ -n "$PREV_END" ] && [ "$GAP" -gt 0 ]; then\n',
    '      # gap: the job must not start before the end of the previous job of this ESX host + GAP min\n',
    '      RG_G=$(( (PREV_END + OFF + GAP * 60 - RG_L + 59) / 60 * 60 ))\n',
    '      if [ "$RG_G" -gt "$RG_T" ]; then\n',
    '        log "gap: the previous job ended $(tstr "$PREV_END"). The next job starts $GAP min or more after that: first start time moved from $(tstr "$RG_T") to $(tstr "$RG_G")"\n',
    '        RG_T=$RG_G\n',
    '      elif [ "$RG_TRY" = 1 ]; then\n',
    '        log "gap: the previous job ended $(tstr "$PREV_END"). The job start is already $GAP min or more after that: no extra wait"\n',
    '      fi\n',
    '    fi\n',
    '    if [ -n "$AT" ]; then\n',
    '      # start time of the plan: the job starts at that time. When it cannot be met, the job starts as soon as possible.\n',
    '      RG_A=$((AT / 60 * 60 - RG_L))\n',
    '      if [ "$RG_A" -ge "$RG_T" ]; then\n',
    '        [ "$RG_TRY" = 1 ] && log "start time: the plan sets the job start of this case to $ATTEXT"\n',
    '        RG_T=$RG_A\n',
    '      elif [ "$RG_TRY" = 1 ]; then\n',
    '        log "WARN the start time $ATTEXT of the plan cannot be met any more (earliest possible job start $(tstr $((RG_T + RG_L)))). Starting as soon as possible."\n',
    '      fi\n',
    '    fi\n',
    '    if [ "$HASMON" = 1 ]; then TMON=$RG_T; TJOB=$((RG_T + RG_L)); else TMON=; TJOB=$RG_T; fi\n',
    '    # job starts on this jump VM are SPACING min or more apart (other ESX hosts and other runs too): move after a nearer one\n',
    '    while :; do\n',
    '      claim_start "$TJOB" "$ME"\n',
    '      RG_C=$?\n',
    '      [ "$RG_C" = 0 ] && break\n',
    '      if [ "$RG_C" != 1 ]; then\n',
    '        pause "the job start times on this jump VM could not be compared ($MD/.lock could not be taken). Nothing of case $CNAME was started."\n',
    '        return 1\n',
    '      fi\n',
    '      RG_M=$((CL_NEAR + SPACING * 60))\n',
    '      log "spacing: the job of $CL_WHO starts $(tstr "$CL_NEAR"), less than $SPACING min from $(tstr "$TJOB"). This job starts at $(tstr "$RG_M")"\n',
    '      [ -n "$TMON" ] && TMON=$((TMON + RG_M - TJOB))\n',
    '      TJOB=$RG_M\n',
    '    done\n',
    '    if [ -n "$AT" ] && [ $((AT / 60 * 60)) != "$TJOB" ]; then\n',
    '      release_start $((AT / 60 * 60)) "$ME"          # the start time of the plan is not used: give it back\n',
    '    fi\n',
    '    # a case that is not checked ends at a time: 2 min before the next case is prepared (NOCHK), or when the maximum\n',
    '    # wait ends, whichever is earlier. The monitoring stop is registered for that time together with the start lines.\n',
    '    TSTOPN=\n',
    '    if [ -n "$NOCHK" ]; then\n',
    '      [ "$MAXW" -gt 0 ] && TSTOPN=$(( (TJOB + MAXW * 60 + 59) / 60 * 60 ))\n',
    '      if [ "$NOCHK" -gt 0 ]; then\n',
    '        RG_H=$(( (NOCHK - 120) / 60 * 60 ))\n',
    '        if [ -z "$TSTOPN" ] || [ "$RG_H" -lt "$TSTOPN" ]; then TSTOPN=$RG_H; fi\n',
    '      fi\n',
    '      if [ -n "$TSTOPN" ] && [ "$TSTOPN" -le $((TJOB + 60)) ]; then\n',
    '        release_start "$TJOB" "$ME"\n',
    '        pause "the job of case $CNAME would start $(tstr "$TJOB"), but the case must end $(tstr "$TSTOPN") (the next case is prepared then, or the maximum wait ends). Nothing of case $CNAME was started. Change the start times in tcgen and generate again."\n',
    '        return 1\n',
    '      fi\n',
    '    fi\n',
    '    WHY=\n',
    '    for RG_VM in $REGVMS; do\n',
    '      mk_vmcron "$RG_VM" "$W/reg.sh" ${TMON:+MS:$TMON} "JOB:$TJOB" ${TSTOPN:+MX:$TSTOPN}\n',
    '      vmrun "$(target "$RG_VM")" "$W/reg.sh" "$W/reg.out" 60\n',
    '      RG_R=$?\n',
    '      if [ "$(tval TCGEN-CRON "$W/reg.out")" != ok ]; then\n',
    '        WHY="vm $RG_VM: crontab lines were not registered (ssh exit $RG_R: $(first "$W/reg.out"))"\n',
    '        break\n',
    '      fi\n',
    '      log "registered on vm $RG_VM:"\n',
    '      grep \'^TCGEN-LINE \' "$W/reg.out" | cut -d\' \' -f2- | sed "s/^/$(stamp)     | /" >> "$LOG"\n',
    '    done\n',
    '    if [ -z "$WHY" ] && has EMS; then\n',
    '      mk_esxcron "$W/ereg.sh" "EMS:$TMON" ${TSTOPN:+EMX:$TSTOPN}\n',
    '      esxrun "$W/ereg.sh" "$W/ereg.out" 60\n',
    '      RG_R=$?\n',
    '      if [ "$(tval TCGEN-CRON "$W/ereg.out")" != ok ]; then\n',
    '        WHY="esx $CHF: crontab lines were not registered (ssh exit $RG_R: $(first "$W/ereg.out"))"\n',
    '      else\n',
    '        log "registered on esx $CHF (UTC):"\n',
    '        grep \'^TCGEN-LINE \' "$W/ereg.out" | cut -d\' \' -f2- | sed "s/^/$(stamp)     | /" >> "$LOG"\n',
    '      fi\n',
    '    fi\n',
    '    if [ -n "$WHY" ]; then\n',
    '      unregister\n',
    '      release_start "$TJOB" "$ME"\n',
    '      pause "$WHY. The lines of case $CNAME were removed, nothing was started."\n',
    '      return 1\n',
    '    fi\n',
    '    RG_N=$(($(now) + OFF)); RG_F=${TMON:-$TJOB}\n',
    '    [ "$RG_N" -le $((RG_F - 15)) ] && break\n',
    '    # too late: cron may not run a line that arrives less than 15 s before its minute. Take every line out again,\n',
    '    # so that the case never starts on only some of its hosts.\n',
    '    log "WARN registering ended $((RG_F - RG_N)) s before the first start time $(tstr "$RG_F"). Removing the lines of this case."\n',
    '    unregister\n',
    '    release_start "$TJOB" "$ME"\n',
    '    if [ $(($(now) + OFF)) -ge $((RG_F - 2)) ]; then\n',
    '      hint_stop\n',
    '      pause "registering the lines of case $CNAME took too long: the first start time $(tstr "$RG_F") passed before the lines were removed. Monitoring or jobs of this case may have started on some hosts. Check them."\n',
    '      return 1\n',
    '    fi\n',
    '    if [ "$RG_TRY" -ge 3 ]; then\n',
    '      pause "registering the lines of case $CNAME was too slow 3 times. The lines were removed, nothing was started."\n',
    '      return 1\n',
    '    fi\n',
    '    RG_AHEAD=$((RG_AHEAD * 2))\n',
    '    log "registering again with a start time $RG_AHEAD s or more ahead"\n',
    '  done\n',
    '  : > "$MD/$TJOB/reg" 2>/dev/null                 # the job is registered: its claim stays when the run ends\n',
    '  say "$SEQ ${TMON:-$TJOB} $TJOB" > "$W/times"     # for cancel: this case has lines on the hosts\n',
    '  [ -n "$TMON" ] && R_MON=$(tstr "$TMON")\n',
    '  R_JOB=$(tstr "$TJOB")\n',
    '  if [ -n "$TMON" ]; then\n',
    '    log "times: monitoring start $R_MON, job start $R_JOB ($LEAD min later, every VM in the same minute, no other job on this jump VM starts within $SPACING min of it)"\n',
    '  else\n',
    '    log "times: job start $R_JOB (every VM in the same minute, no monitoring, no other job on this jump VM starts within $SPACING min of it)"\n',
    '  fi\n',
    '  if [ -n "$NOCHK" ] && [ -n "$TSTOPN" ]; then\n',
    '    log "not checked: the plan sets the start time of this case. End of the case: $(tstr "$TSTOPN") (the monitoring stop is registered for that time, then the lines are removed)"\n',
    '  elif [ -n "$NOCHK" ]; then\n',
    '    log "not checked: the plan sets the start time of this case. It has no end time (last case of this ESX host, no maximum wait)"\n',
    '  fi\n',
    '  return 0\n',
    '}\n',
    '\n',
    '# ---------------------------------------------------------------- step 4: end of the job\n',
    'stop_at_start() {   # a stop request came while tcrun waited for the job start: before the start the lines are removed\n',
    '  WJ_N=$(($(now) + OFF))\n',
    '  if [ "$WJ_N" -lt $((TJOB - 5)) ]; then\n',
    '    log "stop requested before the job start: removing the lines of this case"\n',
    '    unregister\n',
    '    : > "$W/times"\n',
    '    release_start "$TJOB" "$ME"\n',
    '    if [ "$HASMON" = 1 ] && [ "$WJ_N" -ge $((TMON - 30)) ]; then\n',
    '      log "the monitoring of this case has started or is about to start: stopping it"\n',
    '      stop_mon_core\n',
    '    fi\n',
    '    stopped "before the job of case $CNAME started. Its lines were removed."\n',
    '  else\n',
    '    hint_stop\n',
    '    stopped "just after the job of case $CNAME started. The job and the monitoring keep running."\n',
    '  fi\n',
    '}\n',
    'wait_nocheck() {    # a case whose start time is set by the plan (NOCHK): tcrun does not look for the job and does not log in\n',
    '                    # to the VMs while it runs. The case ends at TSTOPN (the monitoring stop was registered together with the\n',
    '                    # start lines), or stays open when it has no end time (last case of the ESX host, no maximum wait)\n',
    '  STEP=wait-start; setstate running "lines registered. job start $R_JOB. The job is not checked (start time of the plan)"\n',
    '  if ! wait_until $((TJOB - MINOFF + 30)); then\n',
    '    stop_at_start\n',
    '    return 1\n',
    '  fi\n',
    '  log "the job start time $R_JOB has passed. The job of case $CNAME is not checked (the plan sets its start time): no login to its VMs while it runs"\n',
    '  if [ -z "$TSTOPN" ]; then\n',
    '    OPEN_CASE=$CNAME\n',
    '    log "case $CNAME stays open: it has no end time (last case of this ESX host, no maximum wait). Its lines stay and its monitoring is not stopped by this run"\n',
    '    log "it is closed when the next run of this ESX host prepares its first case, or by: sh $D/tcrun cancel $CHF"\n',
    '    hint_stop\n',
    '    return 0\n',
    '  fi\n',
    '  STEP=wait-end; setstate running "job started $R_JOB (not checked). The case ends $(tstr "$TSTOPN")"\n',
    '  if ! wait_until $((TSTOPN - MINOFF + 20)); then\n',
    '    hint_stop\n',
    '    stopped "while case $CNAME was running (not checked). The job and the monitoring keep running. The lines of the case stay registered (monitoring stop at $(tstr "$TSTOPN"))."\n',
    '    return 1\n',
    '  fi\n',
    '  R_STOP=$(tstr "$TSTOPN")\n',
    '  log "end of case $CNAME: $R_STOP (time of the plan, the job was not checked)"\n',
    '  STEP=remove-lines; setstate running "removing the lines of the case"\n',
    '  unregister\n',
    '  : > "$W/times"\n',
    '  return 0\n',
    '}\n',
    'poll_all() {\n',
    '  ALLSEEN=1; ALLGONE=1; ALLZERO=1; PSUM=; NOTSEEN=\n',
    '  for PA_VM in $JOBVMS; do\n',
    '    mk_poll "$PA_VM" "$W/poll.sh"\n',
    '    vmrun "$(target "$PA_VM")" "$W/poll.sh" "$W/poll.out" 60\n',
    '    PA_R=$?\n',
    '    PA_N=$(tval TCGEN-PROC "$W/poll.out" | tr -d \' \')\n',
    '    case "$PA_N" in ""|*[!0-9]*) PA_N=unknown ;; esac\n',
    '    PA_S=$(cat "$W/seen.$PA_VM" 2>/dev/null)\n',
    '    PA_Z=$(cat "$W/zero.$PA_VM" 2>/dev/null)\n',
    '    : "${PA_Z:=0}"\n',
    '    if [ "$PA_N" = unknown ]; then\n',
    '      PA_Z=0\n',
    '      PA_T="unknown (ssh exit $PA_R: $(first "$W/poll.out")). Not counted as ended."\n',
    '    elif [ "$PA_N" -gt 0 ]; then\n',
    '      PA_T="$PA_N process(es) running"\n',
    '      if [ -z "$PA_S" ]; then\n',
    '        PA_S=$(now)\n',
    '        say "$PA_S" > "$W/seen.$PA_VM"\n',
    '        PA_T="$PA_T (seen for the first time)"\n',
    '      fi\n',
    '      PA_Z=0\n',
    '    elif [ -n "$PA_S" ]; then\n',
    '      PA_Z=$((PA_Z + 1))\n',
    '      [ "$PA_Z" = 1 ] && now > "$W/gone.$PA_VM"\n',
    '      PA_T="no process ($PA_Z of $GONE in a row)"\n',
    '    else\n',
    '      PA_T="no process yet (not seen since the job start)"\n',
    '    fi\n',
    '    # one line for every login to a VM: the time of the line is when the check of that VM ended (clock of the jump VM)\n',
    '    log "check $WJ_K (case $CNAME) vm $PA_VM: $PA_T"\n',
    '    say "$PA_Z" > "$W/zero.$PA_VM"\n',
    '    if [ -z "$PA_S" ]; then ALLSEEN=0; NOTSEEN="$NOTSEEN $PA_VM"; fi\n',
    '    [ "$PA_Z" -ge "$GONE" ] || ALLGONE=0\n',
    '    [ "$PA_N" = 0 ] && [ -n "$PA_S" ] || ALLZERO=0\n',
    '    PSUM="$PSUM $PA_VM=$PA_N"\n',
    '  done\n',
    '}\n',
    'wait_job() {\n',
    '  STEP=wait-start; setstate running "lines registered. job start $R_JOB"\n',
    '  # While a job runs, the VMs are logged in to as rarely as possible (a login is load on the VM under test):\n',
    '  #   once FIRST s after the job start (is the process there?), then every POLL s.\n',
    '  #   Not seen on every VM at the first check: once more at the end of the start wait.\n',
    '  #   No process on any VM any more: checked again after a short time, until GONE checks in a row agree.\n',
    '  #   No job is running then, so these checks put no load on a measurement.\n',
    '  WJ_FIRST=$((TJOB - MINOFF + FIRST))\n',
    '  if ! wait_until "$WJ_FIRST"; then\n',
    '    stop_at_start\n',
    '    return 1\n',
    '  fi\n',
    '  STEP=wait-job; setstate running "checking the job processes (check 1)"\n',
    '  WJ_CONF=60\n',
    '  [ "$POLL" -lt "$WJ_CONF" ] && WJ_CONF=$POLL\n',
    '  WJ_NS=; WJ_K=0\n',
    '  WJ_SW=$((TJOB - MINOFF + START_WAIT * 60))\n',
    '  WJ_MAX=$(clines MAXWAIT | head -n 1)\n',
    '  case "$WJ_MAX" in ""|*[!0-9]*) WJ_MAX=0 ;; esac\n',
    '  [ "$WJ_MAX" -gt 0 ] && WJ_MAX=$((TJOB - MINOFF + WJ_MAX * 60))\n',
    '  while :; do\n',
    '    WJ_K=$((WJ_K + 1))\n',
    '    poll_all\n',
    '    WJ_N=$(now)\n',
    '    if [ "$ALLSEEN" = 1 ] && [ -z "$R_SEEN" ]; then\n',
    '      R_SEEN=$(stamp)\n',
    '      log "the process is seen on every VM with a job"\n',
    '    fi\n',
    '    [ "$ALLSEEN" = 1 ] && [ "$ALLGONE" = 1 ] && break\n',
    '    if [ "$ALLSEEN" = 0 ] && [ "$WJ_N" -ge "$WJ_SW" ]; then\n',
    '      hint_stop\n',
    '      pause "the process was never seen within $START_WAIT min after the job start on:$NOTSEEN. Check the process name and the job. Nothing was stopped."\n',
