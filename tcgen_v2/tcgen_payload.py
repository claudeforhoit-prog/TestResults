    '    alive "$CR_P" || continue\n',
    '    CR_P=${CR_P%/*}\n',
    '    QWAIT="$QWAIT ${CR_P##*/}"\n',
    '  done\n',
    '  say $$ > "$PIDF"\n',
    '  [ "$CR_LK" = 0 ] && unlock_md\n',
    '  CNAME=; IDX=0; STEP=start; HOW=; HOW_TEXT=; TAKE=; R_DONE=; NREG=0; NREGBAD=0; CR_ALL=\n',
    '  trap \'rm -f "$PIDF"\' 0\n',
    "  trap 'on_signal' 2 15\n",
    "  trap '' 1\n",
