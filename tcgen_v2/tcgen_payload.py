    '    fi\n',
    '    SEQ=\n',
    '    jobs_rest\n',
    '  fi\n',
    '  CNAME=$OS_C\n',
    '  release_mine "$CHF"\n',
    '  setstate stopped "ended by a signal"\n',
    '  exit 1\n',
    '}\n',
    'cmd_run() {\n',
    '  load_plan "$1"\n',
    '  CH=$2\n',
    '  [ -n "$CH" ] || { say "usage: tcrun run <plan> <esx>"; exit 2; }\n',
    '  case "$CH" in -?*|*[!A-Za-z0-9._-]*) say "tcrun: bad ESX host name: $CH"; exit 2 ;; esac\n',
    '  if [ "$PVER" != "$TCRUN_VERSION" ]; then\n',
    '    say "tcrun $TCRUN_VERSION cannot run a plan made by tcgen $PVER. Paste block A of that tcgen again."\n',
    '    exit 3\n',
    '  fi\n',
    '  CHF=$(chfile "$CH")\n',
    '  mkdir -p "$RD" "$LOGDIR" || exit 2\n',
